  nickname_format       text,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
--  Players
-- ---------------------------------------------------------------------------
create table if not exists public.players (
  id                 bigint generated by default as identity primary key,
  guild_id           bigint not null references public.guilds(id) on delete cascade,
  discord_user_id    bigint not null,
  among_us_name      varchar(100) not null,
  nickname           text,
  faceit_player_id   varchar(64),
  faceit_nickname    varchar(100),
  elo                integer not null default 1000,
  peak_elo           integer not null default 1000,
  level              integer not null default 1,
  matches            integer not null default 0,
  wins               integer not null default 0,
  losses             integer not null default 0,
  win_streak         integer not null default 0,
  best_win_streak    integer not null default 0,
  total_voice_seconds bigint not null default 0,
  registered_at      timestamptz not null default now(),
  active             boolean not null default true,
  banned             boolean not null default false,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint uq_players_guild_user    unique (guild_id, discord_user_id),
  constraint uq_players_guild_amongus unique (guild_id, among_us_name)
);
create index if not exists idx_players_guild on public.players(guild_id);
create index if not exists idx_players_discord on public.players(discord_user_id);

create table if not exists public.elo_transactions (
  id               bigint generated by default as identity primary key,
  guild_id         bigint not null references public.guilds(id) on delete cascade,
  player_id        bigint not null references public.players(id) on delete cascade,
  match_id         bigint references public.matches(id) on delete set null,
  old_elo          integer not null,
  change           integer not null,
  new_elo          integer not null,
  reason           varchar(100),
  transaction_type varchar(32) not null default 'MATCH',
  created_by       bigint,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint uq_elo_tx_match_player_type unique (match_id, player_id, transaction_type)
);
create index if not exists idx_elo_player on public.elo_transactions(player_id);

