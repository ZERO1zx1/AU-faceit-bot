  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.guild_settings (
  guild_id              bigint primary key references public.guilds(id) on delete cascade,
  admin_role_id         bigint,
  moderator_role_id     bigint,
  registered_role_id    bigint,
  register_channel_id   bigint,
  register_message_id   bigint,
  queue_channel_id      bigint,
  queue_message_id      bigint,
  leaderboard_channel_id bigint,
  leaderboard_message_id bigint,
  match_category_id     bigint,
  log_channel_id        bigint,
  default_elo           integer not null default 1000,
  win_elo               integer not null default 8,
  loss_elo              integer not null default -6,
